/* ─── Kril → Latin transliteratsiya ─── */
const HASC = (s: string) => /[\u0400-\u04FF]/.test(s);

const CYR_MULTI: [string, string][] = [
  ["Ш","Sh"],["ш","sh"],
  ["Ч","Ch"],["ч","ch"],
  ["Ю","Yu"],["ю","yu"],
  ["Я","Ya"],["я","ya"],
  ["Ё","Yo"],["ё","yo"],
  ["Ж","J"], ["ж","j"],
  ["Ғ","G'"],["ғ","g'"],
  ["Ў","O'"],["ў","o'"],
];
const CYR_SINGLE: [string, string][] = [
  ["А","A"],["а","a"],["Б","B"],["б","b"],["В","V"],["в","v"],
  ["Г","G"],["г","g"],["Д","D"],["д","d"],["Е","E"],["е","e"],
  ["З","Z"],["з","z"],["И","I"],["и","i"],["Й","Y"],["й","y"],
  ["К","K"],["к","k"],["Қ","Q"],["қ","q"],["Л","L"],["л","l"],
  ["М","M"],["м","m"],["Н","N"],["н","n"],["О","O"],["о","o"],
  ["П","P"],["п","p"],["Р","R"],["р","r"],["С","S"],["с","s"],
  ["Т","T"],["т","t"],["У","U"],["у","u"],["Ф","F"],["ф","f"],
  ["Х","X"],["х","x"],["Ҳ","H"],["ҳ","h"],["Ц","Ts"],["ц","ts"],
  ["Э","E"],["э","e"],["Ъ","'"],["ъ","'"],["Ь",""],["ь",""],
  ["Ы","I"],["ы","i"],
];

export function cyrToLatin(text: string): string {
  if (!text || !HASC(text)) return text;
  let res = "";
  let i = 0;
  while (i < text.length) {
    let matched = false;
    for (const [from, to] of CYR_MULTI) {
      if (text.startsWith(from, i)) { res += to; i += from.length; matched = true; break; }
    }
    if (!matched) {
      for (const [from, to] of CYR_SINGLE) {
        if (text.startsWith(from, i)) { res += to; i += from.length; matched = true; break; }
      }
    }
    if (!matched) { res += text[i]; i++; }
  }
  return res;
}

