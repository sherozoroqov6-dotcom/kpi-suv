export type TranslationKey = keyof typeof T.lotin;

interface LangContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
  translit: (text: string) => string;
  /** Ma'lumotlar bazasidan kelgan matnni joriy tilga moslaydi */
  d: (text?: string | null) => string;
}

const LangContext = createContext<LangContextType | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "lotin" || saved === "kril" || saved === "rus") return saved;
    return "lotin";
  });

  const setLang = (l: Lang) => {
    localStorage.setItem(LANG_KEY, l);
    setLangState(l);
  };

  const t = (key: TranslationKey): string => T[lang][key] as string;

  const translit = (text: string): string => {
    if (lang === "kril") return translitToKril(text);
    return text;
  };

  /** Kirilcha matnni lotin tilida ko'rsatish uchun */
  const d = (text?: string | null): string => {
    if (!text) return "";
    if (lang === "lotin") return cyrToLatin(text);
    return text;
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t, translit, d }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used within LangProvider");
  return ctx;
}
